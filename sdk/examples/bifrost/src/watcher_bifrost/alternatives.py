"""Ask the model for alternatives to a refused proposal, through the same Bifrost gateway.

When Watcher refuses a proposal, the bridge shows the model its refused calls
as tool results and asks for another proposal, at most twice per client
request. Each alternative is generated by an ordinary request to Bifrost's
OpenAI Chat Completions route, carrying the original client's own credential
headers, so it uses the same routing, provider keys, budgets and governance as
the client's request. It is graded as its own exchange, in the client's own
Watcher session, before any of it reaches the client. There Watcher has its
own decision for every refused and withheld call the alternative's history
mentions, so it does not take the gateway's synthetic "did not run" results
for calls that ran. (Watcher stores exchanges asynchronously, so if it stores
the alternative first, an allowed call withheld with a refused one can still
be recorded as completed.) A proposal refused here as a repeat was never
graded, so its turn is left out of what later alternatives are graded against.

That request passes through the Watcher plugin again. Grading it there as well
would grade every alternative twice and start a nested recovery, so the bridge
marks it with ``X-Watcher-Alternative``: an expiry and an HMAC over the expiry
and the exact request body, keyed from the Watcher API key, which clients and
providers never see. The plugin asks the bridge to verify the marker; a valid,
unexpired, unused marker passes the exchange through without grading, notice
insertion or recursion, and the outer pass grades the alternative itself. Each
marker is accepted once, so a captured marker cannot be replayed. The plugin
blanks the header before Bifrost builds the provider request.

::

    client ──► Bifrost ──► plugin ──► bridge: proposal refused
                                        │  continuation + marker + client credentials
                                        ▼
               Bifrost ──► plugin (marker valid: pass through) ──► provider
                                        │  alternative
                                        ▼
                        bridge: grade alternative in the client's session
                                        │
                                        ▼
    client ◄── original text + refusal notices + approved alternative

After an escalation, or a third refused proposal, one last text-only generation
(``tool_choice: "none"``) asks the model to stop and put the question to the
user; any call it proposes anyway is withheld without being sent to Watcher.
Everything shares one deadline. A failed or timed-out alternative never
releases a call: the client receives the notices, a sentence saying why no
alternative followed and a fixed question asking the user how to proceed.
``recover`` also returns the IDs of every call withheld in favour of the
delivered completion, which the bridge names when it records that completion.
"""

import asyncio
import hashlib
import hmac
import json
import re
import threading
import time
from collections.abc import Awaitable, Callable
from dataclasses import dataclass, field

import httpx
import structlog

from watcher_bifrost.replan import (
    ALTERNATIVE_FAILED,
    ToolDenial,
    UnmergeableAlternative,
    alternative_message,
    compose,
    continuation,
    denial_notice,
    operation_key,
    stop_notice,
    tool_calls,
)

ALTERNATIVE_HEADER = "x-watcher-alternative"
CHAT_COMPLETIONS_PATH = "/openai/v1/chat/completions"
# The client's proposal plus at most two alternatives, as in the LiteLLM example.
MAX_PROPOSALS = 3
_KEY_LABEL = b"watcher-bifrost alternative marker v1"
# A canonical Unix-seconds expiry (no leading zeros, so each expiry has one
# spelling) and a SHA-256 hex digest; anything else is rejected before
# parsing, so hostile values cannot raise during verification.
_MARKER = re.compile(r"([1-9][0-9]{0,11})\.([0-9a-f]{64})")

logger = structlog.get_logger(__name__)


def marker_key(watcher_api_key: str) -> bytes:
    """Derive the marker key from the Watcher API key, which only the bridge holds."""
    return hmac.new(watcher_api_key.encode(), _KEY_LABEL, hashlib.sha256).digest()


def _mac(key: bytes, expiry: int, body: bytes) -> str:
    return hmac.new(key, f"{expiry}.".encode() + hashlib.sha256(body).digest(), hashlib.sha256).hexdigest()


def sign_marker(key: bytes, body: bytes, expiry: int) -> str:
    """Mark one alternative request body as the bridge's own until ``expiry`` (Unix seconds)."""
    return f"{expiry}.{_mac(key, expiry, body)}"


class MarkerLedger:
    """Verify alternative markers and accept each one at most once.

    Markers are remembered until they expire, so the ledger stays bounded by
    the number of alternatives generated within one deadline. The ledger is
    per bridge process; it is shared by the bridge's request threads.
    """

    def __init__(self, key: bytes) -> None:
        self._key = key
        # Spent markers by (expiry, digest), mapped to their expiry.
        self._used: dict[tuple[int, str], int] = {}
        self._lock = threading.Lock()

    def sign(self, body: bytes, expiry: int) -> str:
        """Mark ``body`` until ``expiry`` (Unix seconds)."""
        return sign_marker(self._key, body, expiry)

    def accept(self, marker: str, body: bytes, now: float | None = None) -> bool:
        """True once for a marker signed for exactly ``body`` and unexpired; malformed, reused markers are False."""
        match = _MARKER.fullmatch(marker)
        current = time.time() if now is None else now
        if match is None or int(match[1]) < current:
            return False
        expiry, digest = int(match[1]), match[2]
        if not hmac.compare_digest(digest, _mac(self._key, expiry, body)):
            return False
        with self._lock:
            for used, until in list(self._used.items()):
                if until < current:
                    del self._used[used]
            if (expiry, digest) in self._used:
                return False
            self._used[(expiry, digest)] = expiry
        return True


class AlternativeFailed(Exception):
    """No alternative could be obtained; the message is fixed text shown to the client."""


@dataclass
class Gateway:
    """Bifrost's client listener, used to generate alternatives as the original client."""

    client: httpx.AsyncClient
    ledger: MarkerLedger
    max_body: int

    async def generate(self, request: dict, credentials: dict[str, str], deadline: float) -> dict:
        """Send one continuation through the gateway and return the provider's completion.

        ``credentials`` are the original client's authentication headers, held
        in memory for this request only. ``deadline`` is on the event loop
        clock; the marker expires with it. The body is read incrementally up to
        ``max_body`` and must arrive uncompressed. Non-2xx statuses, encoded,
        oversized or unreadable bodies raise ``AlternativeFailed``; nothing here
        grades the result.
        """
        body = json.dumps(request, ensure_ascii=False, separators=(",", ":"), allow_nan=False).encode()
        if len(body) > self.max_body:
            raise AlternativeFailed("the conversation is too long to ask for an alternative")
        remaining = deadline - asyncio.get_running_loop().time()
        marker = self.ledger.sign(body, int(time.time() + remaining) + 1)
        headers = {
            **credentials,
            "content-type": "application/json",
            "accept-encoding": "identity",
            ALTERNATIVE_HEADER: marker,
        }
        try:
            async with self.client.stream("POST", CHAT_COMPLETIONS_PATH, content=body, headers=headers) as reply:
                if not 200 <= reply.status_code < 300:
                    logger.warning("alternative_request_failed", status=reply.status_code)
                    raise AlternativeFailed("the provider did not return an alternative")
                if reply.headers.get("content-encoding", "identity").strip().lower() != "identity":
                    raise AlternativeFailed("the provider returned a compressed alternative")
                data = bytearray()
                async for chunk in reply.aiter_bytes():
                    data += chunk
                    if len(data) > self.max_body:
                        raise AlternativeFailed("the alternative exceeds the size limit")
        except httpx.HTTPError as error:
            logger.warning("alternative_request_failed", error_type=type(error).__name__)
            raise AlternativeFailed("the gateway could not be reached") from None
        try:
            response = json.loads(bytes(data))
        except ValueError:
            raise AlternativeFailed("the provider did not return an alternative") from None
        if not isinstance(response, dict):
            raise AlternativeFailed("the provider did not return an alternative")
        return response


@dataclass
class Assessment:
    """Watcher's verdict on one proposal: verified decisions and the refused calls, if any."""

    verified: bool
    denials: list[ToolDenial] = field(default_factory=list)

    @property
    def released(self) -> bool:
        """Every delivered call has a matched allow or deferred decision."""
        return self.verified and not self.denials


# Grades one alternative in the client's session: (history request, response) -> Assessment.
Grader = Callable[[dict, dict], Awaitable[Assessment]]
# Validates an alternative's executable calls, raising ValueError when unsafe.
CallCheck = Callable[[dict], object]


def _repeats(response: dict, forbidden: dict[str, ToolDenial]) -> list[ToolDenial]:
    """Calls in ``response`` that repeat a refused operation under any call ID, with the earlier decision.

    A new call ID must not give a refused operation another chance at a
    stochastic policy decision, so repeats are refused without grading.
    """
    repeats = []
    for call in tool_calls(response):
        earlier = forbidden.get(operation_key(call))
        if earlier is not None:
            repeats.append(
                ToolDenial(
                    tool_use_id=call.tool_use_id,
                    tool_name=call.tool_name,
                    tool_input=call.tool_input,
                    reason=earlier.reason,
                    is_escalation=earlier.is_escalation,
                    user_can_approve=earlier.user_can_approve,
                )
            )
    return repeats


def _graded_history(request: dict, unsubmitted: set[int]) -> dict:
    """``request`` without the messages at ``unsubmitted``, for Watcher to grade an alternative against.

    Those are the turns of proposals refused here as repeats: Watcher never
    evaluated their calls, so it would read their "did not run" results as
    calls that ran and record them as completed. The model still sees them.
    """
    if not unsubmitted:
        return request
    return {**request, "messages": [m for i, m in enumerate(request["messages"]) if i not in unsubmitted]}


_TOO_LARGE = (
    "WATCHER NOTICE (added by Watcher, not written by the assistant): Watcher withheld the proposed tool calls. "
    "None of them ran. The full explanation would exceed the gateway's response size limit."
)


def _fit(original: dict, delivered: dict, question: str, max_body: int) -> dict:
    """``delivered``, or a short text-only reply ending with ``question`` when it would exceed ``max_body``.

    The original response and an alternative can each fit while their
    composition does not, and a withheld response would end the agent's turn
    with an error instead of a question. The short reply keeps the original's
    identity but none of its text, calls or usage, so it always fits.
    """
    if len(json.dumps(delivered, ensure_ascii=False, separators=(",", ":")).encode()) <= max_body:
        return delivered
    created = original.get("created")
    return {
        "id": str(original.get("id", ""))[:256],
        "object": "chat.completion",
        "created": created if type(created) is int else 0,
        "model": str(original.get("model", ""))[:256],
        "choices": [
            {
                "index": 0,
                "message": {"role": "assistant", "content": f"{_TOO_LARGE}\n\n{question}"},
                "finish_reason": "stop",
            }
        ],
    }


def _asks_nothing(response: dict) -> bool:
    """Whether a reply's text cannot carry a question: it is blank, or cut off by the output limit or content filter."""
    choice = response["choices"][0]
    content = choice["message"].get("content")
    blank = not (content.strip() if isinstance(content, str) else content)
    return blank or choice.get("finish_reason") in ("length", "content_filter")


def _failed(original: dict, notices: list[str], denials: list[ToolDenial], reason: str, *, stop: bool) -> dict:
    """The completion after a failed generation: the notices so far, a fixed sentence and a question, with no calls.

    A failed alternative ends with ``ALTERNATIVE_FAILED`` and a failed final
    generation with the stop notice, so the agent's turn always ends by asking
    the user how to proceed rather than on a notice alone.
    """
    if not stop:
        return compose(
            original,
            [*notices, f"No alternative was delivered because {reason}.", ALTERNATIVE_FAILED],
            None,
            release_calls=False,
        )
    return compose(
        original,
        [*notices, f"No final reply was delivered because {reason}."],
        None,
        release_calls=False,
        closing=stop_notice(denials),
    )


async def recover(
    gateway: Gateway,
    grade: Grader,
    check_calls: CallCheck,
    request: dict,
    response: dict,
    denials: list[ToolDenial],
    *,
    credentials: dict[str, str],
    conversation_id: str,
    deadline: float,
) -> tuple[dict, list[str]]:
    """Return the single completion the client receives after ``response`` was refused, and what it withheld.

    ``request`` is the request that produced ``response`` (with the system
    notice), ``denials`` its refusals. Proposal ``n`` (from 0) is refused, its
    notice recorded and its operations remembered; then either an alternative
    is generated and graded (``n`` < 2 and no escalation), or one final
    text-only generation asks the model to stop and ask the user. At most four
    model calls are made per client request (the client's and three here), and
    only the first three can release calls. Every failure releases no call and
    ends with a fixed sentence after the notices so far, then a fixed question
    to the user: ``ALTERNATIVE_FAILED`` after a failed alternative, the stop
    notice after a failed final generation. An approved alternative without
    calls whose text is empty or cut off also ends with ``ALTERNATIVE_FAILED``.
    A completion that would exceed the gateway's ``max_body`` is replaced by a
    short notice ending with the same question.

    A proposal refused here as a repeat is never shown to Watcher: later
    alternatives are graded against history without its turn, though the model
    sees it.

    The second value lists, once each and in order, the calls of every refused
    proposal: the refused calls and the siblings withheld with them, including
    a proposal refused here as a repeat, and an approved alternative's calls
    when the size limit drops them. A call the completion delivers is never
    listed, even when an earlier proposal used its ID. The final generation's
    calls are not listed: they are withheld unevaluated.
    """
    original = response
    withheld: list[str] = []

    def finish(delivered: dict, question: str) -> tuple[dict, list[str]]:
        completion = _fit(original, delivered, question, gateway.max_body)
        if completion is not delivered:
            # The size limit dropped the reply, and with it an approved alternative's calls.
            withheld.extend(call.tool_use_id for call in tool_calls(delivered))
        released = {call.tool_use_id for call in tool_calls(completion)}
        return completion, [call_id for call_id in dict.fromkeys(withheld) if call_id not in released]

    def failed(reason: str, *, stop: bool) -> tuple[dict, list[str]]:
        question = stop_notice(denials) if stop else ALTERNATIVE_FAILED
        return finish(_failed(original, notices, denials, reason, stop=stop), question)

    notices: list[str] = []
    forbidden: dict[str, ToolDenial] = {}
    # Message indexes of turns refused here without grading; see _graded_history.
    unsubmitted: set[int] = set()
    repeated = False
    for number in range(MAX_PROPOSALS):
        refused = {denial.tool_use_id for denial in denials}
        proposed = tool_calls(response)
        withheld.extend(call.tool_use_id for call in proposed)
        cancelled = [call for call in proposed if call.tool_use_id not in refused]
        notices.append(denial_notice(denials, cancelled=cancelled))
        forbidden.update({operation_key(denial): denial for denial in denials})
        stop = number == MAX_PROPOSALS - 1 or any(denial.is_escalation for denial in denials)
        before = len(request["messages"])
        request = continuation(request, response, denials, stop=stop)
        if repeated:
            unsubmitted.update(range(before, len(request["messages"])))
        try:
            async with asyncio.timeout_at(deadline):
                candidate = await gateway.generate(request, credentials, deadline)
                message = alternative_message(candidate)
                if stop:
                    # The model was asked to put the question to the user, so
                    # any call it proposes anyway is withheld without grading.
                    # The stop notice follows its text whenever that text does
                    # not reliably carry the question: calls proposed anyway,
                    # no text, text cut off by the output limit or content
                    # filter, or text with no question mark. A complete reply
                    # that already asks is not asked twice.
                    unasked = (
                        bool(message.get("tool_calls")) or _asks_nothing(candidate) or "?" not in message["content"]
                    )
                    closing = stop_notice(denials) if unasked else None
                    logger.info("final_generation_delivered", conversation_id=conversation_id, proposal=number)
                    return finish(
                        compose(original, notices, candidate, release_calls=False, closing=closing),
                        stop_notice(denials),
                    )
                check_calls(candidate)
                repeats = _repeats(candidate, forbidden)
                repeated = bool(repeats)
                if repeats:
                    logger.info("alternative_repeated", conversation_id=conversation_id, proposal=number + 1)
                    assessment = Assessment(verified=True, denials=repeats)
                else:
                    assessment = await grade(_graded_history(request, unsubmitted), candidate)
                    logger.info(
                        "alternative_evaluated",
                        conversation_id=conversation_id,
                        proposal=number + 1,
                        verified=assessment.verified,
                        denied=len(assessment.denials),
                    )
        except TimeoutError:
            return failed("the time limit was reached", stop=stop)
        except AlternativeFailed as error:
            return failed(str(error), stop=stop)
        except (UnmergeableAlternative, ValueError, KeyError, TypeError) as error:
            logger.warning("alternative_unverifiable", conversation_id=conversation_id, error_type=type(error).__name__)
            reason = (
                "the gateway cannot verify the final reply" if stop else "the gateway cannot verify the alternative"
            )
            return failed(reason, stop=stop)
        except Exception as error:
            logger.warning(
                "alternative_not_evaluated", conversation_id=conversation_id, error_type=type(error).__name__
            )
            # Only an alternative is graded; the final reply fails here only in generation.
            reason = "the final reply could not be generated" if stop else "Watcher did not evaluate the alternative"
            return failed(reason, stop=stop)
        if not assessment.verified:
            return failed("Watcher's decisions do not match the alternative", stop=False)
        if not assessment.denials:
            if not tool_calls(candidate) and _asks_nothing(candidate):
                # A text-only alternative with no text, or cut off by a limit or
                # filter, would end the agent's turn without a question.
                delivered = compose(original, notices, candidate, release_calls=False, closing=ALTERNATIVE_FAILED)
            else:
                delivered = compose(original, notices, candidate, release_calls=True)
            return finish(delivered, ALTERNATIVE_FAILED)
        response, denials = candidate, assessment.denials
    raise AssertionError("The final generation always returns")  # pragma: no cover
