"""Ask the model for alternatives to a refused proposal, back through the same Kong route.

When Watcher refuses a proposal, the bridge shows the model its refused calls
as tool results and asks for another proposal, at most twice per client
request. Each alternative is generated by an ordinary request to the same Kong
route, authenticated with the client's own credential, so Kong's routing,
consumer identity, provider credentials and other plugins apply exactly as
they do to the client. Each alternative is graded before any of it reaches
the client.

That request passes through the Watcher plugin again. Grading it there as
well would grade every alternative twice and start a nested recovery, so the
bridge marks it with ``X-Watcher-Alternative``: an expiry and an HMAC over the
expiry and the exact request body, keyed from the Watcher API key, which
clients and providers never see. The plugin asks the bridge to verify the
marker, then passes a marked exchange through without the system notice,
grading or recovery, and removes the marker before the request goes upstream.

::

    client ──► Kong ──► provider: proposal ──► bridge: Watcher refuses it
                                                 │  continuation + marker
                                                 ▼
               Kong (marker valid: pass through) ──► provider
                                                 │  alternative
                                                 ▼
                       bridge: grade alternative in the client's Watcher session
                                                 │
                                                 ▼
    client ◄── original text + refusal notices + approved alternative

After an escalation, or a third refused proposal, one last generation asks
the model to stop and put the question to the user; it may not call tools,
and any call it proposes anyway is withheld without being sent to Watcher;
then, or when that reply is empty or cut off, a stop notice asks the user.
Everything shares one deadline, which stays below the plugin's bridge
timeout. A failed or timed-out alternative never releases a call: the client
receives the notices with a sentence saying why no alternative followed and a
fixed question asking the user how to proceed.
"""

import asyncio
import hashlib
import hmac
import json
import re
import time
from dataclasses import dataclass, field
from typing import NamedTuple

import httpx
import structlog

from watcher_kong_ai.exchange import (
    MAX_BODY,
    UnsupportedExchange,
    client_calls,
    decode_json,
    evaluate,
)
from watcher_kong_ai.notices import (
    ALTERNATIVE_FAILED,
    Denial,
    MergeError,
    ToolCall,
    check_mergeable,
    compose,
    continuation,
    denial_notice,
    operation_key,
    stop_notice,
    without_calls,
)
from watcher_sdk import AsyncWatcherClient, WatcherAPIError

ALTERNATIVE_HEADER = "x-watcher-alternative"
# The client's proposal plus at most two alternatives, as in the LiteLLM example.
MAX_PROPOSALS = 3
_KEY_LABEL = b"watcher-kong-ai alternative marker v1"
# A Unix-seconds expiry and a SHA-256 hex digest; anything else is rejected
# before parsing, so hostile values cannot raise during verification.
_MARKER = re.compile(r"([0-9]{1,12})\.([0-9a-f]{64})")
# Finish reasons for a reply the provider cut short: the token limit or its content filter.
_CUT_OFF = {"length", "content_filter"}
_NO_ROUTE = "the gateway cannot send an alternative to the client's route"
_TOO_LARGE = (
    "WATCHER NOTICE (added by Watcher, not written by the assistant): Watcher withheld the proposed tool calls. "
    "None of them ran. The full explanation would exceed the gateway's response size limit."
)

logger = structlog.get_logger(__name__)


def marker_key(watcher_api_key: str) -> bytes:
    """Derive the marker key from the Watcher API key, which only the bridge holds."""
    return hmac.new(watcher_api_key.encode(), _KEY_LABEL, hashlib.sha256).digest()


def _mac(key: bytes, expiry: int, body: bytes) -> str:
    return hmac.new(key, f"{expiry}.".encode() + hashlib.sha256(body).digest(), hashlib.sha256).hexdigest()


def sign_marker(key: bytes, body: bytes, expiry: int) -> str:
    """Mark one alternative request body as the bridge's own until ``expiry`` (Unix seconds)."""
    return f"{expiry}.{_mac(key, expiry, body)}"


def verify_marker(key: bytes, marker: str, body: bytes, now: float | None = None) -> bool:
    """True when ``marker`` was signed for exactly ``body`` and has not expired; malformed markers are False."""
    match = _MARKER.fullmatch(marker)
    if match is None or int(match[1]) < (time.time() if now is None else now):
        return False
    return hmac.compare_digest(match[2], _mac(key, int(match[1]), body))


class AlternativeFailed(Exception):
    """No alternative could be obtained; the message is fixed text shown to the client."""


@dataclass
class Gateway:
    """The client's Kong route, used to generate alternatives as that client.

    ``url`` is the full route URL. ``credential`` is the client's own
    authentication header (name and value), forwarded only on these requests
    and never logged or stored; None sends no credential, for routes without
    authentication. ``routing`` holds the headers Kong's router matched the
    client's route on (its Host and the route's header predicates), so the
    alternative reaches the same route when several share a path.
    """

    client: httpx.AsyncClient
    url: str
    marker_key: bytes
    credential: tuple[str, str] | None
    routing: dict[str, str] = field(default_factory=dict)

    async def generate(self, request: dict, deadline: float) -> dict:
        """Send one continuation through Kong and return the provider's completion.

        ``deadline`` is on the event loop clock; the marker expires with it.
        The body is read incrementally up to ``MAX_BODY`` and must arrive
        uncompressed, so a small compressed reply cannot expand in memory.
        Non-2xx statuses, encoded, oversized or unreadable bodies raise
        ``AlternativeFailed``; nothing here grades the result.
        """
        body = json.dumps(request, ensure_ascii=False, separators=(",", ":")).encode()
        if len(body) > MAX_BODY:
            raise AlternativeFailed("the conversation is too long to ask for another reply")
        remaining = deadline - asyncio.get_running_loop().time()
        headers = {
            "content-type": "application/json",
            "accept-encoding": "identity",
            # Only Host, a JSON Content-Type and route predicates the bridge
            # validated; none can replace the marker or credential set below.
            **self.routing,
            ALTERNATIVE_HEADER: sign_marker(self.marker_key, body, int(time.time() + remaining) + 1),
        }
        if self.credential is not None:
            headers[self.credential[0]] = self.credential[1]
        try:
            async with self.client.stream(
                "POST", self.url, content=body, headers=headers, timeout=max(remaining, 0.001)
            ) as reply:
                if not 200 <= reply.status_code < 300:
                    logger.warning("alternative_request_failed", status=reply.status_code)
                    raise AlternativeFailed("the provider did not return a reply")
                if reply.headers.get("content-encoding", "identity").strip().lower() != "identity":
                    raise AlternativeFailed("the provider returned a compressed reply")
                data = bytearray()
                # Identity encoding is required above, so these are the bytes as sent.
                async for chunk in reply.aiter_bytes():
                    data += chunk
                    if len(data) > MAX_BODY:
                        raise AlternativeFailed("the reply exceeds the size limit")
        except httpx.TimeoutException:
            raise TimeoutError from None
        except httpx.HTTPError as error:
            logger.warning("alternative_request_failed", error_type=type(error).__name__)
            raise AlternativeFailed("the gateway could not be reached") from None
        try:
            response = decode_json(bytes(data))
        except ValueError:
            raise AlternativeFailed("the provider did not return a reply") from None
        if not isinstance(response, dict):
            raise AlternativeFailed("the provider did not return a reply")
        return response


@dataclass
class _Recovery:
    """Notices so far, every refused operation and every withheld call ID, for one client request.

    ``unsubmitted`` holds the positions, in every later continuation's
    messages, of proposals refused locally as repeats and their results:
    Watcher never saw those proposals, so they are left out of what it grades.
    """

    notices: list[str] = field(default_factory=list)
    forbidden: dict[str, Denial] = field(default_factory=dict)
    withheld: list[str] = field(default_factory=list)
    unsubmitted: set[int] = field(default_factory=set)

    def withhold(self, calls: list[ToolCall]) -> None:
        """Add ``calls`` to the withheld IDs, in order and without repeats."""
        self.withheld.extend(call.tool_use_id for call in calls if call.tool_use_id not in self.withheld)

    def graded(self, request: dict) -> dict:
        """``request`` as Watcher grades it: without the proposals refused locally, which it never saw.

        Watcher records a call it first sees with a result as having run,
        unless the session already holds a decision for it. A locally refused
        repeat has none, so showing it with the gateway's refusal receipts
        would record calls that never ran. The model still sees it.
        """
        if not self.unsubmitted:
            return request
        kept = [message for index, message in enumerate(request["messages"]) if index not in self.unsubmitted]
        return {**request, "messages": kept}


class Recovered(NamedTuple):
    """The response delivered in place of a refused proposal, and the calls it replaced.

    ``withheld_ids`` lists, in order and without repeats, every call of every
    refused proposal, which the recording of ``response`` names for Watcher.
    A call ID the delivered response itself carries is never listed.
    """

    response: dict
    withheld_ids: list[str]


def _repeats(calls: list[ToolCall], forbidden: dict[str, Denial]) -> list[Denial]:
    """Calls repeating an earlier refused operation under any call ID, refused again for the same reason.

    A new call ID must not give a refused operation another chance at a
    stochastic policy decision, so repeats are refused without grading.
    """
    repeats = []
    for call in calls:
        earlier = forbidden.get(operation_key(call))
        if earlier is not None:
            repeats.append(
                Denial(
                    tool_use_id=call.tool_use_id,
                    tool_name=call.tool_name,
                    tool_input=call.tool_input,
                    reason=earlier.reason,
                    is_escalation=earlier.is_escalation,
                    user_can_approve=earlier.user_can_approve,
                )
            )
    return repeats


def _final_reply(response: dict) -> tuple[int, bool]:
    """How many calls the final generation proposed, and whether its reply fails to ask the user anything.

    Its calls are always withheld unevaluated, so only the envelope is
    checked and their arguments are never parsed: a call cut off mid-argument
    must not stop the user being asked. A reply with calls, no text, text
    without a question mark, or cut off by the token limit or the provider's
    content filter counts as unanswered: it would end the agent's turn with
    nobody asked how to proceed. A complete reply that already asks needs no
    second question. A malformed envelope raises ``UnsupportedExchange``.
    """
    choices = response.get("choices") if isinstance(response, dict) else None
    if not isinstance(choices, list) or len(choices) != 1 or not isinstance(choices[0], dict):
        raise UnsupportedExchange("Exactly one complete response choice is required")
    choice = choices[0]
    message = choice.get("message")
    if (
        type(choice.get("index")) is not int
        or choice["index"] != 0
        or not isinstance(message, dict)
        or message.get("role") != "assistant"
        or message.get("function_call") is not None
        or choice.get("finish_reason") not in {"stop", "tool_calls", *_CUT_OFF}
    ):
        raise UnsupportedExchange("Unsupported final reply")
    calls = message.get("tool_calls") or []
    if not isinstance(calls, list):
        raise UnsupportedExchange("Invalid tool calls")
    content = message.get("content")
    answered = isinstance(content, str) and bool(content.strip()) and "?" in content
    return len(calls), bool(calls) or choice["finish_reason"] in _CUT_OFF or not answered


def _failure_reason(error: Exception, *, final: bool = False) -> str:
    """Fixed client-facing text for why no reply followed; never provider or Watcher content."""
    subject = "final reply" if final else "alternative"
    if isinstance(error, TimeoutError):
        return "the time limit was reached"
    if isinstance(error, AlternativeFailed):
        return str(error)
    if isinstance(error, (UnsupportedExchange, MergeError)):
        return f"the gateway cannot verify the {subject}"
    return "the final reply could not be read" if final else "Watcher did not evaluate the alternative"


async def recover(
    watcher: AsyncWatcherClient,
    gateway: Gateway | None,
    request: dict,
    response: dict,
    denials: list[Denial],
    *,
    conversation_id: str,
    user_agent: str | None,
    deadline: float,
    max_body: int = MAX_BODY,
) -> Recovered:
    """Build the response delivered in place of a refused proposal, within ``deadline``.

    ``request`` is the client's request as the provider received it (with the
    system notice), ``response`` the refused proposal and ``denials`` its
    refusals. Refusing proposal ``n`` (from 0) stops after it when ``n`` is 2
    or any refusal is an escalation; otherwise an alternative is generated and
    graded. The returned completion keeps the original's identity and carries
    the original text, every notice, and then an approved alternative, the
    final generation's text (plus ``stop_notice`` if it proposed calls
    anyway, or its reply was empty or cut off), or a sentence saying why no
    alternative followed and then ``ALTERNATIVE_FAILED``, a fixed question
    asking the user how to proceed. An approved alternative with neither
    calls nor non-blank text also ends with ``ALTERNATIVE_FAILED``. Any error after the original decision
    ends the response that way; none releases a call. If the final
    generation itself fails, its sentence is followed by ``stop_notice``, so
    the user is always asked. Without a ``gateway`` (the client's route
    cannot be reached again) the first notice is followed by that sentence
    and question at once. A response that would exceed ``max_body`` (the
    plugin's configured limit, at most ``MAX_BODY``) is replaced by a short
    notice that still ends with a question.

    Each alternative is graded in the client's own Watcher session
    (``conversation_id``). Its request repeats the refused calls with the
    gateway's refusal receipts as their results, and Watcher records a call
    first seen with a result as having run unless the session already holds
    a decision for it. Every call Watcher graded has one; a proposal refused
    locally as a repeat was never graded, so it is left out of what Watcher
    sees (``_Recovery.graded``). The result also lists every withheld call,
    including any an approved alternative loses to the size limit, for the
    recording of the delivered response.
    """
    state = _Recovery()
    proposal = response
    replacement: dict | None = None
    trailer: str | None = None
    repeated = False
    for number in range(MAX_PROPOSALS):
        calls = client_calls(proposal)
        state.withhold(calls)
        refused = {denial.tool_use_id for denial in denials}
        state.notices.append(
            denial_notice(denials, cancelled=[call for call in calls if call.tool_use_id not in refused])
        )
        state.forbidden.update({operation_key(denial): denial for denial in denials})
        stop = number == MAX_PROPOSALS - 1 or any(denial.is_escalation for denial in denials)
        shown = len(request["messages"])
        request = continuation(request, proposal, calls, denials, stop=stop)
        if repeated:
            state.unsubmitted.update(range(shown, len(request["messages"])))
            repeated = False
        if gateway is None:
            state.notices.append(f"No {'final reply' if stop else 'alternative'} was delivered because {_NO_ROUTE}.")
            trailer = stop_notice(denials) if stop else ALTERNATIVE_FAILED
            break
        try:
            async with asyncio.timeout_at(deadline):
                proposal = await gateway.generate(request, deadline)
                if stop:
                    # The model was asked to put the question to the user, so
                    # any call it proposes anyway is withheld unevaluated. A
                    # reply with calls, no text, no question mark, or cut off by
                    # a limit or filter asks nothing, so the stop notice asks
                    # the user instead.
                    withheld, unanswered = _final_reply(proposal)
                    proposal = without_calls(proposal)
                    check_mergeable(proposal)
                    replacement = proposal
                    if unanswered:
                        trailer = stop_notice(denials)
                    logger.info(
                        "final_generation_delivered",
                        conversation_id=conversation_id,
                        withheld_unevaluated=withheld,
                        unanswered=unanswered,
                    )
                    break
                alternative_calls = client_calls(proposal)
                check_mergeable(proposal)
                denials = _repeats(alternative_calls, state.forbidden)
                if denials:
                    # Refused locally: nothing is submitted, so Watcher holds no decision for it.
                    logger.info("alternative_repeated", conversation_id=conversation_id, attempt=number + 1)
                    repeated = True
                    continue
                evaluation = await evaluate(
                    watcher,
                    state.graded(request),
                    proposal,
                    conversation_id=conversation_id,
                    user_agent=user_agent,
                    provider="kong",
                )
        except Exception as error:
            if isinstance(error, WatcherAPIError):
                logger.warning("alternative_failed", conversation_id=conversation_id, watcher_status=error.status_code)
            else:
                logger.warning("alternative_failed", conversation_id=conversation_id, error_type=type(error).__name__)
            if stop:
                # The final generation was to ask the user; ask with the stop notice instead.
                state.notices.append(f"No final reply was delivered because {_failure_reason(error, final=True)}.")
                trailer = stop_notice(denials)
            else:
                state.notices.append(f"No alternative was delivered because {_failure_reason(error)}.")
                trailer = ALTERNATIVE_FAILED
            break
        logger.info(
            "alternative_evaluated",
            conversation_id=conversation_id,
            attempt=number + 1,
            verified=evaluation.verified,
            denied=len(evaluation.denials),
        )
        if not evaluation.verified:
            # Watcher may have recorded some of these calls; none reaches the client.
            state.withhold(alternative_calls)
            state.notices.append(
                "No alternative was delivered because Watcher's decisions do not match the alternative."
            )
            trailer = ALTERNATIVE_FAILED
            break
        if not evaluation.denials:
            replacement = proposal
            content = proposal["choices"][0]["message"].get("content")
            if not alternative_calls and not (content.strip() if isinstance(content, str) else content):
                # A text-only alternative with no text would end the agent's
                # turn without a question. (One cut off by a limit or filter
                # never gets here: ``client_calls`` refuses it as a failure.)
                trailer = ALTERNATIVE_FAILED
            break
        denials = evaluation.denials
    delivered = compose(response, "\n\n".join(state.notices), replacement, trailer=trailer)
    if len(json.dumps(delivered, ensure_ascii=False).encode()) > max_body:
        # The short notice drops the reply, so it still needs a question: the
        # one recovery chose, else the one matching how recovery ended.
        question = trailer or (stop_notice(denials) if stop else ALTERNATIVE_FAILED)
        delivered = compose(response, _TOO_LARGE, None, trailer=question)
        if replacement is not None and replacement["choices"][0]["message"].get("tool_calls"):
            # An approved alternative's calls are dropped with it.
            state.withhold(client_calls(replacement))
    released = {call["id"] for call in delivered["choices"][0]["message"].get("tool_calls") or []}
    return Recovered(delivered, [call_id for call_id in state.withheld if call_id not in released])
