"""Ask the model for alternatives to a refused proposal, through the same Portkey gateway.

When Watcher refuses a proposal, the bridge shows the model its refused calls
as tool results and asks for another proposal, at most twice per client
request. Each alternative is generated by an ordinary request to the
launcher's own Chat Completions listener, so it uses the same Portkey route,
provider configuration and credentials as the client's request, and is graded
in the client's own Watcher conversation before any of it reaches the client.

The launcher would otherwise install the Watcher webhooks on that request
too, grading every alternative twice and starting a nested recovery. The
bridge therefore marks it with ``X-Watcher-Alternative``: an expiry, a random
nonce and an HMAC over both and the exact request body, keyed from the bridge
token, which clients and providers never see. Portkey's webhooks receive neither request
headers nor the exact body bytes, so the launcher verifies the marker itself,
accepts each marker once, removes the header and dispatches the request with
the provider configuration only. The outer pass grades the alternative.

::

    client ──► launcher ──► Portkey ──► provider ──► /evaluate: proposal refused
                                                        │  continuation + marker
                                                        ▼
               launcher (marker valid, no hooks) ──► Portkey ──► provider
                                                        │  alternative
                                                        ▼
                         /evaluate: grade alternative in the client's session
                                                        │
                                                        ▼
    client ◄── original text + refusal notices + approved alternative

After an escalation, or a third refused proposal, one last generation asks the
model to stop and ask the user, with ``tool_choice`` ``"none"``; any call it
proposes anyway is withheld without being sent to Watcher, without decoding
its arguments. When that reply proposes calls, has no text or is cut off by
the token limit, or the generation fails, a fixed closing notice asks the user
instead, so the agent's turn never ends without a question. Everything shares
one deadline that stays below the launcher's webhook timeout. A failed or
timed-out attempt never releases a call: the client receives the notices, a
sentence saying why no alternative followed and a fixed question asking the
user how to proceed.

Every Watcher exchange declares that refused calls are withheld, so Watcher
records a refusal as blocked. Grading alternatives in the client's own
conversation keeps the refused proposals they carry as history from being
recorded as calls that ran: Watcher already holds a decision for each of
those calls. A proposal refused locally as a repeat was never graded, so it
and its results are left out of what Watcher grades, though the model still
sees them. After a refusal, ``record_delivery`` records the reply the client
received, naming every call withheld in its favour, so Watcher can show those
calls before it.
"""

import asyncio
import hashlib
import hmac
import json
import secrets
import time
from copy import deepcopy
from dataclasses import dataclass
from typing import Any

import httpx
import structlog

from watcher_portkey.exchange import (
    UnsupportedExchange,
    UnverifiedDecision,
    client_calls,
    decide,
    decode_json,
)
from watcher_portkey.replan import (
    ALTERNATIVE_FAILED,
    ToolDenial,
    build_continuation,
    check_composable,
    compose,
    denial_notice,
    operation_key,
    stop_notice,
    tool_calls,
)
from watcher_sdk import AsyncWatcherClient, WatcherAPIError

ALTERNATIVE_HEADER = "x-watcher-alternative"
# The client's proposal plus at most two alternatives; a fourth model call, the
# final text-only generation, can never release a tool call.
MAX_PROPOSALS = 3
# Must match the label in gateway/server.mjs, which verifies the marker.
_KEY_LABEL = b"watcher-portkey alternative marker v1"

logger = structlog.get_logger(__name__)


def marker_key(bridge_token: str) -> bytes:
    """Derive the marker key from the bridge token, which only the launcher and bridge hold."""
    return hmac.new(bridge_token.encode(), _KEY_LABEL, hashlib.sha256).digest()


def sign_marker(key: bytes, body: bytes, expiry: int, nonce: str | None = None) -> str:
    """Mark one alternative request body as the bridge's own until ``expiry`` (Unix seconds).

    The marker is ``<expiry>.<nonce>.<mac>``: a 16-byte random nonce in hex,
    then the HMAC-SHA256 over ``"<expiry>.<nonce>."`` and the body's SHA-256.
    The launcher accepts each marker once, so the nonce keeps two recoveries
    whose continuations happen to be byte-identical within the same second
    from sharing a marker. ``nonce`` is fixed only by tests.
    """
    nonce = secrets.token_hex(16) if nonce is None else nonce
    signed = f"{expiry}.{nonce}.".encode() + hashlib.sha256(body).digest()
    return f"{expiry}.{nonce}.{hmac.new(key, signed, hashlib.sha256).hexdigest()}"


class AlternativeFailed(Exception):
    """No alternative could be obtained; the message is fixed text shown to the client."""


class StructuredOutputRefused(Exception):
    """A call was refused in a reply the client asked to receive as JSON.

    Watcher's text notices would make that JSON unparseable, so the bridge
    withholds the response with an explicit error instead of rewriting it, and
    asks for no alternative. Watcher has already recorded the refusal.
    """


def _structured_output(request: dict) -> bool:
    """Whether the client asked for JSON content (``json_object`` or ``json_schema``)."""
    response_format = request.get("response_format")
    return isinstance(response_format, dict) and response_format.get("type") in {"json_object", "json_schema"}


@dataclass(frozen=True)
class Gateway:
    """The launcher's Chat Completions listener, reached with the gateway's client key.

    The launcher accepts one shared client key, so this is the same credential
    the client presented; it is held in memory and never logged. ``transport``
    replaces httpx's network transport, for tests.
    """

    url: str
    client_key: str
    marker_key: bytes
    max_body: int
    transport: httpx.AsyncBaseTransport | None = None

    async def generate(self, request: dict, deadline: float) -> dict:
        """Send one continuation through the gateway and return the provider's completion.

        ``deadline`` is on the event loop clock; the marker expires with it.
        The body is read incrementally up to ``max_body`` and must arrive
        uncompressed, so a small compressed reply cannot expand in memory.
        Non-2xx statuses, encoded, oversized or unreadable bodies raise
        ``AlternativeFailed``; nothing here grades the result.
        """
        body = json.dumps(request, ensure_ascii=False, separators=(",", ":")).encode()
        if len(body) > self.max_body:
            raise AlternativeFailed("the conversation is too long to ask for an alternative")
        remaining = deadline - asyncio.get_running_loop().time()
        headers = {
            "authorization": "Bearer " + self.client_key,
            "content-type": "application/json",
            "accept-encoding": "identity",
            ALTERNATIVE_HEADER: sign_marker(self.marker_key, body, int(time.time() + remaining) + 1),
        }
        try:
            async with (
                httpx.AsyncClient(timeout=max(remaining, 0.001), transport=self.transport) as client,
                client.stream("POST", self.url, content=body, headers=headers) as reply,
            ):
                if not 200 <= reply.status_code < 300:
                    logger.warning("alternative_request_failed", status=reply.status_code)
                    raise AlternativeFailed("the provider did not return an alternative")
                if reply.headers.get("content-encoding", "identity").strip().lower() != "identity":
                    raise AlternativeFailed("the provider returned a compressed alternative")
                data = bytearray()
                async for chunk in reply.aiter_bytes():
                    data += chunk
                    if len(data) > self.max_body:
                        raise AlternativeFailed("the alternative exceeds the size limit")
        except httpx.HTTPError as error:
            logger.warning("alternative_request_failed", error_type=type(error).__name__)
            raise AlternativeFailed("the gateway could not be reached") from None
        try:
            response = decode_json(bytes(data))
        except (UnsupportedExchange, ValueError):
            raise AlternativeFailed("the provider did not return an alternative") from None
        if not isinstance(response, dict):
            raise AlternativeFailed("the provider did not return an alternative")
        return response


@dataclass(frozen=True)
class Delivery:
    """The reply composed after a refusal, and the calls withheld in its favour.

    ``withheld_ids`` lists every call of every refused proposal, in order,
    except a call the reply itself delivers; ``record_delivery`` names them to
    Watcher. Calls the final generation proposed are not listed: Watcher never
    evaluated them.
    """

    response: dict
    withheld_ids: list[str]


@dataclass(frozen=True)
class _Exchange:
    """Client-facing metadata every Watcher submission for one client request shares."""

    conversation_id: str
    url: str
    provider: str
    user_agent: str | None


def _final_reply(response: Any) -> tuple[dict, bool]:
    """Normalize the final generation into deliverable text; return it and whether it asks nothing.

    The final generation can never release a call, so its calls are removed
    without decoding their arguments: a reply cut off mid-call still has text
    worth delivering. The copy's turn ends with ``finish_reason`` ``"stop"``.
    The flag is true when the reply proposed calls, has no text, did not stop
    normally (for example cut off by the token limit) or has no question mark:
    such a reply puts no question to the user, so the caller closes it with the
    fixed one. A complete reply that already asks is not asked twice. Raises
    ``ValueError`` when there is no single assistant message with mergeable text.
    """
    choices = response.get("choices") if isinstance(response, dict) else None
    if not isinstance(choices, list) or len(choices) != 1 or not isinstance(choices[0], dict):
        raise UnsupportedExchange("One response choice is required")
    message = choices[0].get("message")
    if not isinstance(message, dict) or message.get("role") != "assistant":
        raise UnsupportedExchange("Response must contain an assistant message")
    result = deepcopy(response)
    choice = result["choices"][0]
    text = choice["message"]
    proposed = bool(text.pop("tool_calls", None)) | (text.pop("function_call", None) is not None)
    check_composable(result)
    asks_nothing = proposed or _asks_nothing(result) or "?" not in text["content"]
    choice["finish_reason"] = "stop"
    return result, asks_nothing


def _asks_nothing(response: dict) -> bool:
    """Whether a reply puts nothing to the user: its text is blank, or it did not stop normally."""
    choice = response["choices"][0]
    content = choice["message"].get("content")
    return not (content.strip() if isinstance(content, str) else content) or choice.get("finish_reason") != "stop"


async def respond(
    watcher: AsyncWatcherClient,
    gateway: Gateway,
    request: dict,
    response: dict,
    *,
    conversation_id: str,
    url: str,
    provider: str,
    user_agent: str | None,
    deadline: float,
) -> Delivery | None:
    """Decide one client request's provider response; None releases it unchanged.

    Otherwise returns the ``Delivery`` of the composed completion: the original text, a notice per
    refused proposal and, when one was found, an approved alternative's text and
    calls, or the final generation's text (followed by the stop notice when it
    proposed calls, has no text or was cut off). ``deadline`` (event loop clock)
    bounds the original decision, every alternative and the final generation.
    A failed or unverifiable original decision raises, which withholds the
    response, as does a refusal in a reply the client asked to receive as JSON
    (``StructuredOutputRefused``). A failed alternative ends the notices with a
    sentence saying why and ``ALTERNATIVE_FAILED``; a failed final generation
    ends them with a sentence saying why and the stop notice. Either way the
    user is still asked how to proceed.
    """
    exchange = _Exchange(conversation_id, url, provider, user_agent)
    loop = asyncio.get_running_loop()
    async with asyncio.timeout_at(deadline):
        denials = await decide(
            watcher,
            request,
            response,
            conversation_id=conversation_id,
            url=url,
            provider=provider,
            user_agent=user_agent,
            timeout=max(deadline - loop.time(), 0.001),
        )
    if not denials:
        return None
    if _structured_output(request):
        logger.info("structured_output_refused", conversation_id=conversation_id, refused=len(denials))
        raise StructuredOutputRefused
    check_composable(response)
    notices: list[str] = []
    forbidden: dict[str, ToolDenial] = {}
    candidate = response
    replacement: dict | None = None
    closing: str | None = None
    withheld: list[str] = []
    # Positions, in every later continuation's messages, of proposals refused
    # locally as repeats and their results; Watcher never graded them.
    unsubmitted: set[int] = set()
    repeated = False
    for number in range(MAX_PROPOSALS):
        refused_ids = {denial.tool_use_id for denial in denials}
        withheld += [call.tool_use_id for call in tool_calls(candidate)]
        cancelled = [call for call in tool_calls(candidate) if call.tool_use_id not in refused_ids]
        notices.append(denial_notice(denials, cancelled=cancelled))
        forbidden.update({operation_key(denial): denial for denial in denials})
        final = number == MAX_PROPOSALS - 1 or any(denial.is_escalation for denial in denials)
        shown = len(request["messages"])
        request = build_continuation(request, candidate, denials, stop=final)
        if repeated:
            unsubmitted.update(range(shown, len(request["messages"])))
        if final:
            # The model was asked to put the question to the user, so any call
            # it proposes anyway is withheld without evaluation. A reply that
            # asks nothing, or no reply at all, is closed with the fixed question.
            reply = await _final(gateway, request, exchange, deadline=deadline)
            if isinstance(reply, str):
                notices.append(f"No final reply was delivered because {reply}.")
                closing = stop_notice(denials)
            else:
                replacement, asks_nothing = reply
                closing = stop_notice(denials) if asks_nothing else None
            break
        graded = {
            **request,
            "messages": [item for index, item in enumerate(request["messages"]) if index not in unsubmitted],
        }
        outcome = await _attempt(
            watcher, gateway, request, graded, forbidden, exchange, deadline=deadline, attempt=number + 1
        )
        if isinstance(outcome, str):
            notices.append(f"No alternative was delivered because {outcome}.")
            closing = ALTERNATIVE_FAILED
            break
        candidate, denials, repeated = outcome
        if not denials:
            replacement = candidate
            if not tool_calls(candidate) and _asks_nothing(candidate):
                # A text-only alternative with no text, or cut off by a limit or
                # filter, would end the agent's turn without a question.
                replacement = deepcopy(candidate)
                replacement["choices"][0]["finish_reason"] = "stop"
                closing = ALTERNATIVE_FAILED
            break
    released = {call.tool_use_id for call in tool_calls(replacement)} if replacement is not None else set()
    logger.info(
        "recovery_finished",
        conversation_id=conversation_id,
        notices=len(notices),
        delivered_alternative=bool(released),
    )
    return Delivery(
        compose(response, replacement, "\n\n".join(notices), closing=closing),
        list(dict.fromkeys(call_id for call_id in withheld if call_id not in released)),
    )


async def record_delivery(
    watcher: AsyncWatcherClient,
    request: dict,
    delivery: Delivery,
    *,
    conversation_id: str,
    url: str,
    provider: str,
    user_agent: str | None,
    timeout: float,
) -> None:
    """Record the reply the client received after a refusal; failures are logged, never raised.

    ``request`` is the client's request as graded. The reply's delivered calls
    were already graded with their alternative, so they move into the
    recorded history (as the assistant message the client's next request
    carries) and the recorded response is an empty assistant message: nothing
    is graded again. A text-only reply is recorded as the response itself.
    The withheld calls are named so Watcher can show them before the reply.
    """
    reply = delivery.response
    message = reply["choices"][0]["message"]
    if message.get("tool_calls"):
        request = {**request, "messages": [*request["messages"], message]}
        empty = {"role": "assistant", "content": None}
        reply = {**reply, "choices": [{**reply["choices"][0], "message": empty, "finish_reason": "stop"}]}
    try:
        await decide(
            watcher,
            request,
            reply,
            conversation_id=conversation_id,
            url=url,
            provider=provider,
            user_agent=user_agent,
            timeout=timeout,
            withheld_ids=delivery.withheld_ids or None,
        )
    except Exception as error:
        logger.warning("delivery_not_recorded", conversation_id=conversation_id, error_type=type(error).__name__)


async def _final(gateway: Gateway, request: dict, exchange: _Exchange, *, deadline: float) -> tuple[dict, bool] | str:
    """Generate the final, text-only reply; return ``_final_reply``'s result, or why it failed.

    Nothing here is sent to Watcher. The returned reason is fixed text for the
    client, never provider content.
    """
    try:
        async with asyncio.timeout_at(deadline):
            return _final_reply(await gateway.generate(request, deadline))
    except TimeoutError:
        return "the time limit was reached"
    except (AlternativeFailed, ValueError) as error:
        logger.warning("final_reply_failed", conversation_id=exchange.conversation_id, error_type=type(error).__name__)
        return "the provider did not return a usable reply"


async def _attempt(
    watcher: AsyncWatcherClient,
    gateway: Gateway,
    request: dict,
    graded: dict,
    forbidden: dict[str, ToolDenial],
    exchange: _Exchange,
    *,
    deadline: float,
    attempt: int,
) -> tuple[dict, list[ToolDenial], bool] | str:
    """Generate one alternative and decide it; return it, its refusals and whether it was a repeat, or why it failed.

    ``request`` (the continuation) is sent to the model. A call repeating an
    earlier refused operation under any ID is refused again with the earlier
    reason, without grading, and the flag is true. Otherwise the alternative
    is graded in the client's own conversation with ``graded`` as its history:
    the continuation without proposals refused locally as repeats, which
    Watcher never graded and would otherwise record as calls that ran. The
    returned reason is fixed text for the client, never provider content.
    """
    loop = asyncio.get_running_loop()
    try:
        async with asyncio.timeout_at(deadline):
            candidate = await gateway.generate(request, deadline)
            client_calls(candidate)
            check_composable(candidate)
            repeats = [
                ToolDenial(
                    tool_use_id=call.tool_use_id,
                    tool_name=call.tool_name,
                    tool_input=call.tool_input,
                    reason=earlier.reason,
                    is_escalation=earlier.is_escalation,
                    user_can_approve=earlier.user_can_approve,
                )
                for call in tool_calls(candidate)
                if (earlier := forbidden.get(operation_key(call))) is not None
            ]
            if repeats:
                logger.info("alternative_repeated", conversation_id=exchange.conversation_id, attempt=attempt)
                return candidate, repeats, True
            denials = await decide(
                watcher,
                graded,
                candidate,
                conversation_id=exchange.conversation_id,
                url=exchange.url,
                provider=exchange.provider,
                user_agent=exchange.user_agent,
                timeout=max(deadline - loop.time(), 0.001),
            )
    except TimeoutError:
        return "the time limit was reached"
    except AlternativeFailed as error:
        return str(error)
    except UnverifiedDecision:
        logger.warning("alternative_unverified", conversation_id=exchange.conversation_id, attempt=attempt)
        return "Watcher's decisions do not match the alternative"
    except ValueError as error:
        logger.warning(
            "alternative_unverifiable", conversation_id=exchange.conversation_id, error_type=type(error).__name__
        )
        return "the gateway cannot verify the alternative"
    except WatcherAPIError as error:
        logger.warning(
            "alternative_not_evaluated", conversation_id=exchange.conversation_id, watcher_status=error.status_code
        )
        return "Watcher did not evaluate the alternative"
    except Exception as error:
        logger.warning(
            "alternative_not_evaluated", conversation_id=exchange.conversation_id, error_type=type(error).__name__
        )
        return "Watcher did not evaluate the alternative"
    logger.info(
        "alternative_evaluated",
        conversation_id=exchange.conversation_id,
        attempt=attempt,
        denied=len(denials),
    )
    return candidate, denials, False
